function initialLanguage(): Language {
  const stored = localStorage.getItem(STORAGE_LANGUAGE);
  if (stored === 'en' || stored === 'he') return stored;
  return navigator.language.toLowerCase().startsWith('he') ? 'he' : 'en';
}

function initialTheme(): Theme {
  const stored = localStorage.getItem(STORAGE_THEME);
  if (stored === 'light' || stored === 'dark') return stored;
  return window.matchMedia?.('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
}

function interpolate(value: string, variables?: Variables): string {
  if (!variables) return value;
  return value.replace(/{{(\w+)}}/g, (_, name: string) => String(variables[name] ?? `{{${name}}}`));
}

const TranslationContext = createContext<TranslationContextValue | null>(null);

export function PreferencesProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(initialLanguage);
  const [theme, setTheme] = useState<Theme>(initialTheme);
  const locale = language === 'he' ? 'he-IL' : 'en-US';
  const direction = language === 'he' ? 'rtl' : 'ltr';

  useLayoutEffect(() => {
    const root = document.documentElement;
    root.lang = language;
    root.dir = direction;
    localStorage.setItem(STORAGE_LANGUAGE, language);
  }, [direction, language]);

  useLayoutEffect(() => {
    document.documentElement.dataset.theme = theme;
    document.documentElement.style.colorScheme = theme;
    document.querySelector<HTMLMetaElement>('meta[name="theme-color"]')?.setAttribute('content', theme === 'dark' ? '#343943' : '#f5f6f8');
    localStorage.setItem(STORAGE_THEME, theme);
    window.kanbanos?.appearance?.setTheme(theme);
  }, [theme]);

  const t = useCallback((key: string, variables?: Variables) => {
    const ipcError = /^Error invoking remote method '[^']+':\s*(.*)$/s.exec(key);
    const normalizedKey = ipcError ? ipcError[1].replace(/^(?:Error:\s*)+/, '') : key;
    const value = language === 'he' ? HEBREW_TRANSLATIONS[normalizedKey] : undefined;
    return interpolate(value ?? normalizedKey, variables);
  }, [language]);

  const value = useMemo<TranslationContextValue>(() => ({
    language,
    locale,
    direction,
    theme,
    setLanguage,
    setTheme,
    toggleTheme: () => setTheme((current) => current === 'light' ? 'dark' : 'light'),
    t,
  }), [direction, language, locale, t, theme]);

  return <TranslationContext.Provider value={value}>{children}</TranslationContext.Provider>;
}

export function useI18n(): TranslationContextValue {
  const context = useContext(TranslationContext);
  if (!context) throw new Error('useI18n must be used inside PreferencesProvider');
  return context;
}
